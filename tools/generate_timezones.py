"""Generate compact, shared UTC-offset tables from an official tzdata wheel.

Only public-domain IANA data is included in the generated firmware table.
Python's ZoneInfo expands the TZif future rules; firmware needs no online
timezone service or process-global TZ setting. Regenerate after tzdata updates.
"""
import argparse
from datetime import datetime, timezone
import hashlib
import io
import re
import struct
from pathlib import Path
from zoneinfo import ZoneInfo
import zipfile

START = int(datetime(2020, 1, 1, tzinfo=timezone.utc).timestamp())
END = int(datetime(2101, 1, 1, tzinfo=timezone.utc).timestamp())


def explicit_transitions(data):
    def block(start, width):
        counts = struct.unpack_from('>6I', data, start + 20)
        gmt, std, leaps, times, types, chars = counts
        position = start + 44
        values = struct.unpack_from('>' + ('q' if width == 8 else 'i') * times, data, position)
        end = position + width * times + times + 6 * types + chars + leaps * (width + 4) + std + gmt
        return values, end
    values, end = block(0, 4)
    if data[4:5] in (b'2', b'3', b'4'):
        values, end = block(end, 8)
    return values, data[end:].strip(b'\n')


def rules(data):
    zone = ZoneInfo.from_file(io.BytesIO(data))
    def offset(timestamp):
        return int(datetime.fromtimestamp(timestamp, timezone.utc).astimezone(zone).utcoffset().total_seconds())
    given, footer = explicit_transitions(data)
    candidates = {stamp for stamp in given if START < stamp < END}
    if b',' in footer:
        cursor = max(START, given[-1] if given else START)
        previous = offset(cursor)
        while cursor < END - 1:
            following = min(cursor + 86400, END - 1)
            following_offset = offset(following)
            if following_offset != previous:
                low, high = cursor, following
                while high - low > 1:
                    middle = (low + high) // 2
                    if offset(middle) == previous:
                        low = middle
                    else:
                        high = middle
                candidates.add(high)
            cursor, previous = following, following_offset
    initial = previous = offset(START)
    transitions = []
    for stamp in sorted(candidates):
        value = offset(stamp)
        if value != previous:
            transitions.append((stamp - START, value))
            previous = value
    return initial, tuple(transitions)


def generate(wheel, output):
    cache, groups, names = {}, {}, []
    with zipfile.ZipFile(wheel) as archive:
        version = re.search(r'IANA_VERSION\s*=\s*"([^"]+)"', archive.read('tzdata/__init__.py').decode())[1]
        for name in sorted(archive.read('tzdata/zones').decode().splitlines()):
            data = archive.read('tzdata/zoneinfo/' + name)
            digest = hashlib.sha256(data).digest()
            if digest not in cache:
                cache[digest] = rules(data)
            group = cache[digest]
            index = groups.setdefault(group, len(groups))
            names.append((name, index))
    lines = [f'/* Generated by tools/generate_timezones.py; IANA {version}, public-domain data. */',
             f'#define APP_TIMEZONE_START INT64_C({START})', f'#define APP_TIMEZONE_END INT64_C({END})',
             'static const timezone_transition_t TIMEZONE_TRANSITIONS[] = {']
    ranges, first = [], 0
    for initial, transitions in groups:
        ranges.append((first, len(transitions), initial))
        first += len(transitions)
        lines.extend(f'    {{{stamp}U, {value}}},' for stamp, value in transitions)
    assert first < 65536
    lines.extend(['};', 'static const timezone_group_t TIMEZONE_GROUPS[] = {'])
    lines.extend(f'    {{{first}, {count}, {initial}}},' for first, count, initial in ranges)
    lines.extend(['};', 'static const timezone_name_t TIMEZONE_NAMES[] = {'])
    lines.extend(f'    {{"{name}", {index}}},' for name, index in names)
    lines.extend(['};', ''])
    output.write_text('\n'.join(lines), encoding='ascii', newline='\n')
    print(f'IANA {version}: {len(names)} zones, {len(groups)} offset groups, {first} transitions')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('wheel', type=Path)
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parent.parent / 'main/app_timezones.inc')
    args = parser.parse_args()
    generate(args.wheel, args.output)
